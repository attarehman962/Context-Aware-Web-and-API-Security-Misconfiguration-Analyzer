"""Catalog of all 58 checks (spec section 13).

Each entry holds the *predefined* metadata for a rule: name, category, official
CVSS v3.1 vector (never invented at runtime; the base score is computed from it,
and for an id that has a checks.yaml spec it is the spec's vector), impact, remediation,
references, and -- where the check cannot be fully confirmed in unauthenticated
black-box mode -- an honest ``limitation`` note (spec sections 47-48).

Detection logic lives in the per-category modules; this file is data only.
"""
