// Copies Asim's final evaluation tables (eval/results/final/*.csv) into
// src/data/evaluation.json for the /evaluation page. Runs before `dev` and
// `build`; the JSON is committed because the Docker build context
// (frontend/) cannot see ../eval. src/data/evaluation.test.ts fails if the
// committed copy drifts from the CSVs.
//
//   node scripts/sync-eval.mjs           # write src/data/evaluation.json
//   node scripts/sync-eval.mjs --check   # exit 1 if it is out of date
//
// The page reads these columns by name. If a CSV's header changes, the sync
// stops here instead of drawing a wrong chart: update EXPECTED and the page
// together (and confirm the meaning of new columns with Asim).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const EVAL_DIR = path.resolve(here, "../../eval/results/final");
export const OUT_FILE = path.resolve(here, "../src/data/evaluation.json");

export const EXPECTED = {
  tools: [
    "tool",
    "target",
    "tp",
    "fp",
    "fn",
    "tn",
    "precision",
    "recall",
    "fpr",
    "scan_seconds",
  ],
  ranking: [
    "target",
    "priority_items",
    "critical_items",
    "ndcg10_base",
    "ndcg10_context",
    "first_critical_base",
    "first_critical_context",
  ],
  mapping: [
    "check_id",
    "title",
    "base_vector",
    "base",
    "low",
    "medium",
    "high",
    "critical",
  ],
  classifier: [
    "families",
    "split",
    "n",
    "accuracy",
    "macro_f1",
    "off_by_two_or_more",
    "recall_low",
    "recall_medium",
    "recall_high",
    "recall_critical",
  ],
  confusion: ["true \\ predicted", "LOW", "MEDIUM", "HIGH", "CRITICAL"],
};

/** RFC 4180 CSV: quoted fields, doubled quotes, CRLF or LF. */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((f) => f !== ""));
}

const NUMBER = /^-?\d+(\.\d+)?$/;

/** Rows as objects; numbers become numbers and empty cells null. */
export function readTable(name, dir = EVAL_DIR) {
  const file = path.join(dir, `${name}.csv`);
  const [header, ...rows] = parseCsv(readFileSync(file, "utf8"));
  const expected = EXPECTED[name];
  if (header.join(",") !== expected.join(",")) {
    throw new Error(
      `${name}.csv columns changed.\n  expected: ${expected.join(",")}\n` +
        `  found:    ${header.join(",")}\n` +
        "Update EXPECTED in scripts/sync-eval.mjs and the /evaluation page.",
    );
  }
  return rows.map((cells) =>
    Object.fromEntries(
      header.map((col, i) => {
        const v = (cells[i] ?? "").trim();
        return [col, v === "" ? null : NUMBER.test(v) ? Number(v) : v];
      }),
    ),
  );
}

export function buildEvaluation(dir = EVAL_DIR) {
  return {
    $comment:
      "Generated by scripts/sync-eval.mjs from eval/results/final/*.csv. Do not edit.",
    source: "eval/results/final",
    ...Object.fromEntries(
      Object.keys(EXPECTED).map((name) => [name, readTable(name, dir)]),
    ),
  };
}

export function serialise(data) {
  return JSON.stringify(data, null, 2) + "\n";
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (!existsSync(EVAL_DIR)) {
    // Docker build: only frontend/ is in the context; keep the committed copy.
    console.log(
      "sync-eval: eval/results/final not found, using the committed src/data/evaluation.json",
    );
    process.exit(0);
  }
  const text = serialise(buildEvaluation());
  const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (current !== text) {
      console.error(
        "sync-eval: src/data/evaluation.json is out of date; run npm run sync:eval",
      );
      process.exit(1);
    }
  } else if (current !== text) {
    writeFileSync(OUT_FILE, text);
    console.log("sync-eval: wrote src/data/evaluation.json");
  }
}
